import type { FormEvent, KeyboardEvent, RefObject } from 'react'

import { Button } from '@/components/ui/button'
import { Textarea } from '@/components/ui/textarea'
import { MAX_QUESTION_LENGTH } from '@/data/ask/prompt'

type AskFormProps = {
  question: string
  onChange: (question: string) => void
  onSubmit: () => void
  pending: boolean
  turnstileContainer: RefObject<HTMLDivElement | null>
}

export function AskForm({ question, onChange, onSubmit, pending, turnstileContainer }: AskFormProps) {
  const submit = (event: FormEvent) => {
    event.preventDefault()
    if (!pending) onSubmit()
  }
  // Enter asks; Shift+Enter adds a line.
  const onKeyDown = (event: KeyboardEvent<HTMLTextAreaElement>) => {
    if (event.key === 'Enter' && !event.shiftKey) {
      event.preventDefault()
      if (!pending) onSubmit()
    }
  }
  const empty = question.trim().length === 0

  return (
    <form onSubmit={submit} className="mt-8">
      <label htmlFor="ask-question" className="block text-sm font-medium">
        Your question
      </label>
      <Textarea
        id="ask-question"
        name="question"
        value={question}
        onChange={(event) => onChange(event.target.value)}
        onKeyDown={onKeyDown}
        maxLength={MAX_QUESTION_LENGTH}
        rows={2}
        placeholder="Which genre do viewers over 55 rate highest?"
        autoComplete="off"
        className="mt-2 text-base md:text-base"
        aria-describedby="ask-note ask-count"
      />
      <div className="mt-3 flex flex-wrap items-center justify-between gap-3">
        <p id="ask-count" className="text-xs text-muted-foreground tabular-nums">
          {question.length}/{MAX_QUESTION_LENGTH}
        </p>
        <Button type="submit" size="lg" disabled={pending || empty} aria-disabled={pending || empty}>
          {pending ? 'Asking…' : 'Ask the data'}
        </Button>
      </div>
      <div ref={turnstileContainer} className="mt-3 empty:hidden" />
      <p id="ask-note" className="mt-4 text-sm text-muted-foreground">
        Answers are generated by AI and computed from the synthetic dataset. Check the SQL to see
        exactly what was counted.
      </p>
    </form>
  )
}
