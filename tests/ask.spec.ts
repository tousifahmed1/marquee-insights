import { expect, test } from '@playwright/test'

import { gotoHydrated } from './helpers'

const EXAMPLE = 'Top five shows by satisfaction in the Midwest'

// The first click may be a miss on a fresh cache (one model call); the second
// visit must be a hit, which is what the example buttons promise.
test('an example question answers from the cache and shows its SQL', async ({ page }) => {
  test.setTimeout(90_000)
  await gotoHydrated(page, '/ask')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Ask the data')

  await page.getByRole('button', { name: EXAMPLE }).click()
  const answer = page.getByRole('article')
  await expect(answer).toBeVisible({ timeout: 45_000 })
  await expect(answer.getByRole('heading', { level: 2 })).not.toHaveText('')
  await expect(answer.getByRole('region', { name: /Result rows/ })).toBeVisible()

  await page.reload()
  await page.locator('html[data-hydrated="true"]').waitFor({ state: 'attached' })
  await page.getByRole('button', { name: EXAMPLE }).click()
  await expect(page.getByRole('article')).toBeVisible({ timeout: 15_000 })
  await expect(page.getByText('cached', { exact: true })).toBeVisible()

  const sqlPanel = page.getByRole('group').filter({ hasText: 'Show SQL' })
  await sqlPanel.locator('summary').click()
  await expect(sqlPanel.locator('code')).toContainText(/^SELECT/)
  await expect(sqlPanel.locator('code')).toContainText('LIMIT 5')
  await expect(sqlPanel.getByRole('button', { name: 'Copy SQL' })).toBeVisible()
})

test('/ask renders on the server and is never cached', async ({ request }) => {
  const response = await request.get('/ask')
  expect(response.status()).toBe(200)
  expect(response.headers()['cache-control']).toBe('no-store')
  const html = await response.text()
  expect(html).toContain('Ask the data')
  expect(html).toContain('Try an example')
  expect(html).toContain('Answers are generated by AI')
})
